// ─── Cart Reload Loader ───────────────────────────────────────────────────────
// How long (ms) to wait after a successful cart update before reloading.
// Give the Shopify sections API time to settle before we reload.
const CART_RELOAD_DELAY = 800;

function getOrCreateCartLoader() {
  let overlay = document.getElementById('cart-reload-loader');
  if (!overlay) {
    overlay = document.createElement('div');
    overlay.id = 'cart-reload-loader';
    overlay.setAttribute('aria-hidden', 'true');
    overlay.innerHTML = `
      <div class="cart-reload-loader__spinner"></div>
      <span class="cart-reload-loader__label">Updating cart…</span>
    `;
    const style = document.createElement('style');
    style.textContent = `
      #cart-reload-loader {
        position: fixed;
        inset: 0;
        background: rgba(255, 255, 255, 0.82);
        display: flex;
        flex-direction: column;
        align-items: center;
        justify-content: center;
        z-index: 99999;
        opacity: 0;
        pointer-events: none;
        transition: opacity 0.22s ease;
      }
      #cart-reload-loader.is-visible {
        opacity: 1;
        pointer-events: all;
      }
      .cart-reload-loader__spinner {
        width: 38px;
        height: 38px;
        border: 3px solid #e5e7eb;
        border-top-color: #111;
        border-radius: 50%;
        animation: cartLoaderSpin 0.7s linear infinite;
      }
      .cart-reload-loader__label {
        margin-top: 14px;
        font-size: 13px;
        letter-spacing: 0.03em;
        color: #555;
        font-family: inherit;
      }
      @keyframes cartLoaderSpin {
        to { transform: rotate(360deg); }
      }
    `;
    document.head.appendChild(style);
    document.body.appendChild(overlay);
  }
  return overlay;
}

function showCartLoader() {
  getOrCreateCartLoader().classList.add('is-visible');
}

function hideCartLoader() {
  const overlay = document.getElementById('cart-reload-loader');
  if (overlay) overlay.classList.remove('is-visible');
}

function reloadAfterCartUpdate() {
  showCartLoader();
  setTimeout(() => {
    window.location.reload();
  }, CART_RELOAD_DELAY);
}
